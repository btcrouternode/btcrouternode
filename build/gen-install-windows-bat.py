"""Generate files/www/knots/tls/install-windows.bat from install-windows.ps1.

P4 (review 2026-10-10): the .bat used to download install-windows.ps1 from
http://rnode.local at run time and execute it elevated with
-ExecutionPolicy Bypass — a second unauthenticated code fetch. Now the
PowerShell script is embedded in the .bat: cmd writes the part after the
marker to a private temp .ps1 and runs that (the elevated relaunch needs a
real file). No network fetch of code at all.

Run after editing install-windows.ps1:  python3 build/gen-install-windows-bat.py
tests/host/test-tls-installers.sh fails if the two drift apart.
"""
import pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TLS = ROOT / "files/www/knots/tls"
ps1 = (TLS / "install-windows.ps1").read_text(encoding="ascii")
MARK = "#KNOTS-PS1-BEGIN"

head = r"""@echo off
REM SPDX-License-Identifier: GPL-2.0-only
REM Bitcoin Node - one-click HTTPS trust helper (N13 / U17 / P4).
REM Double-click this file. It may ask for your computer Administrator password.
REM Optional:  install-windows.bat http://rnode.local -CheckOnly   (verify only)
REM Self-contained: the PowerShell installer is embedded below (no download of
REM code). It only trusts a certificate restricted to this router.
REM GENERATED by build/gen-install-windows-bat.py from install-windows.ps1 - do not edit.
setlocal
set ROUTER=http://rnode.local
if not "%~1"=="" set ROUTER=%~1
set "PS1=%TEMP%\knots-install-%RANDOM%%RANDOM%.ps1"
powershell.exe -NoProfile -ExecutionPolicy Bypass -Command "$t=[IO.File]::ReadAllText('%~f0'); $m='#KNOTS-'+'PS1-BEGIN'; $i=$t.LastIndexOf($m); if ($i -lt 0) { exit 1 }; [IO.File]::WriteAllText($env:PS1, $t.Substring($i), [Text.Encoding]::ASCII)"
if errorlevel 1 (
  echo ERROR: could not unpack the installer.
  pause
  exit /b 1
)
REM %~dp0 = folder this .bat was saved in (fallback knots-ca.crt lives there);
REM %2..%5 pass extra options through, e.g. -CheckOnly.
powershell.exe -NoProfile -ExecutionPolicy Bypass -File "%PS1%" -Router "%ROUTER%" -BatDir "%~dp0." %2 %3 %4 %5
set "RC=%errorlevel%"
del /q "%PS1%" >nul 2>&1
echo.
REM Success closes by itself (owner, 2026-10-25: same feel as the Mac) - the
REM browser is already opening the secure page. A failure stays open to read.
if not "%RC%"=="0" (
  echo The certificate was NOT installed - see the message above.
  pause
  endlocal
  exit /b %RC%
)
if /i "%~2"=="-CheckOnly" (
  pause
  endlocal
  goto :eof
)
echo Done - this computer now trusts the router. The secure Setup page is opening.
timeout /t 4 /nobreak >nul 2>&1
endlocal
goto :eof
"""
out = head + MARK + "\n" + ps1
if MARK in ps1:
    sys.exit("marker must not appear inside install-windows.ps1")
data = out.replace("\r\n", "\n").replace("\n", "\r\n").encode("ascii")
(TLS / "install-windows.bat").write_bytes(data)
print("wrote", TLS / "install-windows.bat", len(data), "bytes")
